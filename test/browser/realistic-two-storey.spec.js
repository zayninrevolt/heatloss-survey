'use strict';
const {test,expect}=require('@playwright/test');
const fs=require('node:fs/promises');
const {realisticSurvey}=require('../helpers/realistic-two-storey-driver');
const {chromiumPdfPages}=require('../helpers/chromium-pdf.cjs');
test('realistic mixed two-storey survey reconciles longhand, emitters, persistence and native PDF',async({page},testInfo)=>{
 test.setTimeout(180000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const fixture=await realisticSurvey(page);
 const state=await page.evaluate(()=>({result:window.heatLossResultsV60,ref:window.referenceNaturalCheckV1,data:getData()}));
 await fs.writeFile(testInfo.outputPath('resolved-survey.json'),JSON.stringify({fixture,...state},null,2));
 expect(state.result.includedRooms).toHaveLength(7);expect(state.result.incompleteRooms).toHaveLength(0);
 expect(state.result.provisional).toBe(false);expect(state.ref.available,state.ref.reason).toBe(true);
 expect(state.result.ventilationAge.category).toBe('pre-2000');
 let total=0,areaSum=0;const oracle=[];
 for(const role of fixture.roles){
  const room=state.result.includedRooms.find(r=>r.key===role.key);
  const area=role.length*role.width,dt=role.temp+3;
  const externalWall=role.wallU*(role.external*2.4-role.windowArea-(role.doorArea||0))*dt;
  const openings=(role.windowU*role.windowArea+3*(role.doorArea||0))*dt;
  const floor=role.floorU*area*(role.floorAir?dt:role.temp-10);
  const roof=role.roofU*area*dt;
  const internalArea=(2*(role.length+role.width)-role.external)*2.4;
  const doorArea=0.762*1.981;
  const internal=((internalArea-doorArea)*1.76+doorArea*2)*(role.temp-role.adjacent);
  const fabric=externalWall+openings+floor+roof+internal;
  const ventilation=0.33*role.ach*area*2.4*dt;
  const bridge=0.15*(role.external*2.4+(role.floorU?area:0)+(role.roofU?area:0))*dt;
  const watts=fabric+ventilation+bridge;
  const property=watts-internal;
  expect(room.wallU,role.name).toBe(role.wallU);expect(room.windowU,role.name).toBe(role.windowU);
  // The legacy result calls fabric PLUS bridging 'fabricWatts'; the independent
  // raw fabric calculation stays separate here so bridging is not counted twice.
  expect(room.fabricWatts,role.name).toBeCloseTo(fabric+bridge,8);
  expect(room.ventilationWatts,role.name).toBeCloseTo(ventilation,8);
  expect(room.bridgeWatts,role.name).toBeCloseTo(bridge,8);
  expect(room.totalWatts,role.name).toBeCloseTo(watts,8);
  expect(room.propertyWatts,role.name).toBeCloseTo(property,8);
  expect(room.existingRadiatorAdequate).toBe(room.existingRadiator.watts>=room.radiatorRequirementWatts);
  const chosen=room.effectiveRadiator;
  if(chosen) expect(chosen.watts+1e-8).toBeGreaterThanOrEqual(room.radiatorRequirementWatts);
  else expect(room.warnings.join(' ')).toMatch(/no.*option|review|below/i);
  total+=property;areaSum+=area;
  oracle.push({room:role.name,fabric,ventilation,bridge,internal,totalWatts:watts,propertyWatts:property});
 }
 expect(state.result.totalWatts).toBeCloseTo(total,8);expect(state.result.totalArea).toBe(areaSum);
 const transfers=state.ref.result.rooms.flatMap(r=>r.elements).filter(e=>e.name.startsWith('intermediate-'));
 expect(transfers.reduce((s,e)=>s+e.totalWatts,0)).toBeCloseTo(0,8);
 await page.reload();await page.locator('#radsTab').click();
 expect(await page.evaluate(()=>getData())).toEqual(state.data);
 expect(await page.evaluate(()=>JSON.stringify(window.heatLossResultsV60))).toBe(JSON.stringify(state.result));
 const downloadPromise=page.waitForEvent('download');await page.evaluate(()=>saveJson());
 const download=await downloadPromise;const backup=await fs.readFile(await download.path(),'utf8');
 expect(JSON.parse(backup)).toEqual(state.data);
 await page.evaluate(()=>localStorage.clear());await page.reload();
 await page.locator('#loadFile').setInputFiles({name:'synthetic-two-storey.json',mimeType:'application/json',buffer:Buffer.from(backup)});
 expect(await page.evaluate(()=>getData())).toEqual(state.data);
 await page.locator('#radsTab').click();
 page.on('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Save PDFs',exact:true}).click();
 const popup=page.waitForEvent('popup');
 await page.getByRole('button',{name:'Save Front + Rads + Heat Loss PDF',exact:true}).click();
 const print=await popup;await print.waitForLoadState('load');await print.evaluate(()=>document.fonts.ready);
 for(const role of fixture.roles) await expect(print.locator('#heatLossAssumptionsSheetV61')).toContainText(role.name);
 await expect(print.locator('#heatLossAssumptionsSheetV61')).toContainText('1997');
 await expect(print.locator('#heatLossAssumptionsSheetV61')).toContainText('45°C flow / 35°C return');
 const buffer=await print.pdf({path:testInfo.outputPath('synthetic-two-storey.pdf'),printBackground:true,preferCSSPageSize:true});
 const pages=chromiumPdfPages(buffer);
 expect(pages.every(p=>p.textCodes>40||p.textRuns>1)).toBe(true);
 await testInfo.attach('synthetic-survey-verification',{body:JSON.stringify({fixture,oracle,totalWatts:total,totalArea:areaSum,pdfPages:pages,state},null,2),contentType:'application/json'});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.selectRadiatorRoomV60('hallway'));
 await page.screenshot({path:testInfo.outputPath('phone-hallway.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});
